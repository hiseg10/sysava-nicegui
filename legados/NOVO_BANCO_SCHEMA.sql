-- 8. Funcoes de resolucao de disciplinas (ver scripts/migracao_aliases_id_subjects.sql)
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION normalize_subject_name(p text)
RETURNS text LANGUAGE sql STABLE AS $$
  SELECT regexp_replace(upper(unaccent(coalesce(p, ''))), '[^A-Z0-9]', '', 'g');
$$;

DROP FUNCTION IF EXISTS resolver_subject_id(text);
DROP FUNCTION IF EXISTS resolver_subject_exato(text);
DROP FUNCTION IF EXISTS resolver_subject_raiz(integer);

CREATE OR REPLACE FUNCTION resolver_subject_raiz(p_id bigint)
RETURNS bigint LANGUAGE sql STABLE AS $$
  WITH RECURSIVE up AS (
    SELECT id, aliases_id, 1 AS lvl FROM public.subjects WHERE id = p_id
    UNION ALL
    SELECT s.id, s.aliases_id, up.lvl + 1
    FROM public.subjects s
    JOIN up ON s.id = up.aliases_id
    WHERE up.lvl < 10
  )
  SELECT id FROM up WHERE aliases_id IS NULL ORDER BY lvl DESC LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION resolver_subject_exato(p_nome text)
RETURNS bigint LANGUAGE plpgsql STABLE AS $$
DECLARE
  v_norm text := normalize_subject_name(p_nome);
  v_id   bigint;
BEGIN
  IF v_norm = '' THEN RETURN NULL; END IF;
  SELECT id INTO v_id FROM public.subjects WHERE normalize_subject_name(name) = v_norm LIMIT 1;
  IF v_id IS NULL THEN
    SELECT s.id INTO v_id
      FROM public.subjects s
     WHERE EXISTS (
       SELECT 1 FROM jsonb_array_elements_text(s.aliases) a
        WHERE normalize_subject_name(a) = v_norm
     )
     LIMIT 1;
  END IF;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION resolver_subject_id(p_nome text)
RETURNS bigint LANGUAGE plpgsql STABLE AS $$
DECLARE v_id bigint := resolver_subject_exato(p_nome);
BEGIN
  IF v_id IS NULL THEN RETURN NULL; END IF;
  RETURN resolver_subject_raiz(v_id);
END;
$$;

-- -----------------------------------------------------------------------------
-- 9. Utilitario para o restore (reajusta as sequencias apos inserir IDs manuais)
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.reset_identity_sequences()
RETURNS void LANGUAGE plpgsql AS $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT c.relname AS seq, t.relname AS tbl, a.attname AS col
    FROM pg_class c
    JOIN pg_depend d ON d.objid = c.oid
    JOIN pg_class t ON d.refobjid = t.oid
    JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = d.refobjsubid
    WHERE c.relkind = 'S' AND t.relnamespace = 'public'::regnamespace
  LOOP
    EXECUTE format(
      'SELECT setval(%L, COALESCE((SELECT MAX(%I) FROM public.%I), 1))',
      r.seq, r.col, r.tbl
    );
  END LOOP;
END;
$$;

GRANT EXECUTE ON FUNCTION public.reset_identity_sequences() TO anon, authenticated, service_role;

